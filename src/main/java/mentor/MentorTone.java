    /** Facts behind a daily reminder; every number comes from the database. */
    record Progress(int accepted, int total, String stepType, boolean debt, int streak, int todaySteps,
                    int streakGoal, int hoursLeft, boolean ignored) {}

    /** The smallest concrete action for a step, so a reminder asks for something doable right now. */
    static String quickStart(String stepType) {
        return "Минимум на 10 минут: " + switch (stepType) {
            case "Теория" -> "открой первую ссылку и пришли одну фразу, что понял. Хоть кривую.";
            case "Алгоритмы" -> "открой задачу и пришли идею в двух строках, без кода.";
            case "Собеседование" -> "ответь на вопрос одной фразой, как сказал бы вслух. Можно голосом.";
            default -> "открой проект и пришли, что запустил и что увидел.";
        } + "\nЖми «Начинаю» — через 40 минут спрошу результат.";
    }

    static String brokenPromise(long seed) {
        return choose(List.of(
                "Ты нажал «Начинаю» 40 минут назад. Ответа нет. Это был план или пиар-ход?",
                "40 минут прошло. «Начинаю» без результата — это как коммит без изменений.",
                "Ну что, начал? Судя по тишине, начал листать ленту. Кидай что есть, даже кривое."
        ), seed);
    }

    /** A reminder that reacts to real progress. Later slots get pushier. */
    static String dailyReminder(int slot, Progress p, long seed) {
        if (p.ignored()) {
            return choose(List.of(
                    "Прошлое напоминание ты прочитал и молча забил. Я всё вижу.",
                    "Игнор засчитан. Урок — нет.",
                    "Тишина в чате — это не прогресс."
            ), seed) + " " + dailyReminder(slot, new Progress(p.accepted(), p.total(), p.stepType(), p.debt(),
                    p.streak(), p.todaySteps(), p.streakGoal(), p.hoursLeft(), false), seed);
        }
        String opener;
        if (p.debt()) {
            opener = choose(List.of(
                    "Вчерашний урок до сих пор висит: " + p.accepted() + " из " + p.total() + ". Долг сам себя не закроет.",
                    "Ты там живой? Вчерашний урок застрял на шаге " + (p.accepted() + 1) + " из " + p.total() + ".",
                    "Второй день на шаге " + (p.accepted() + 1) + " из " + p.total() + ". Это уже не лень, это стратегия."
            ), seed + slot);
        } else if (p.accepted() == 0) {
            opener = switch (slot) {
                case 0 -> choose(List.of(
                        "Доброе утро. Сегодняшний урок открыт, а ты пока на нуле. Самое время это исправить.",
                        "Утро. Урок ждёт, 0 из " + p.total() + ". Первый шаг — теория, это даже не больно."), seed);
                case 1 -> "Полдня прошло, а урок всё ещё 0 из " + p.total() + ". Десять минут — и первый шаг закрыт.";
                case 2 -> "Вечер, 0 из " + p.total() + ". Собес сам себя не пройдёт, а лень сама себя не победит.";
                default -> choose(List.of(
                        "Ну что, опять «завтра»? До 04:00 " + hours(p.hoursLeft()) + ", а у тебя 0 из " + p.total() + ".",
                        "0 из " + p.total() + ". Я не злюсь, я просто записываю. До 04:00 " + hours(p.hoursLeft()) + ".",
                        "Последний звонок: 0 из " + p.total() + ". Закрой хотя бы теорию — это минут 20 по делу."), seed + slot);
            };
        } else {
            opener = slot <= 2
                    ? choose(List.of(
                            "Уже " + p.accepted() + " из " + p.total() + ". Неплохо, но не расслабляйся.",
                            p.accepted() + " из " + p.total() + ". Разогнался — не тормози."), seed + slot)
                    : choose(List.of(
                            p.accepted() + " из " + p.total() + ", до 04:00 " + hours(p.hoursLeft()) + ". Добей.",
                            "Осталось " + (p.total() - p.accepted()) + " шаг(а). Не бросай на полпути, это самое тупое место для остановки."),
                    seed + slot);
        }
        String streak = p.todaySteps() >= p.streakGoal()
                ? (p.streak() > 1 ? "\nСтрик: " + p.streak() + " дн. подряд." : "")
                : p.streak() > 0
                        ? "\nСтрик " + p.streak() + " дн. сгорит в 04:00, если не закроешь ещё "
                                + (p.streakGoal() - p.todaySteps()) + " шаг(а)."
                        : "";
        return opener + streak;
    }

    private static String hours(int hours) {
        return hours <= 0 ? "меньше часа" : hours + " ч";
    }

